OWNER_ID = 7955185125

def get_role(uid, cid):
    try:
        if int(uid) == OWNER_ID:
            return "owner"
    except:
        pass
    try:
        from db import is_sudo
        if is_sudo(uid):
            return "player_owner"
    except:
        pass
    try:
        import turso_db as sqlite3
        conn = sqlite3.connect(str(Path.home() / "skteam_music" / "data" / "settings.db"), timeout=3)
        r = conn.execute("SELECT 1 FROM sk_group_owners WHERE chat_id=? AND user_id=?", (cid, uid)).fetchone()
        conn.close()
        if r:
            return "player_owner"
    except:
        pass
    try:
        from db import is_music_authorized
        if is_music_authorized(cid, uid):
            return "music_admin"
    except:
        pass
    return "user"

